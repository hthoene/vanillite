/// A list of strings (block ids, …), written as a TOML array or as one comma-separated string
/// (for environment variables and panels).
impl RuleValue for Vec<String> {
    const SHAPE: ValueShape = ValueShape::of(ValueType::Text);
    fn from_toml(value: &toml::Value) -> Result<Self, String> {
        match value {
            toml::Value::Array(items) => items
                .iter()
                .map(|item| {
                    item.as_str()
                        .map(|s| s.trim().to_owned())
                        .ok_or_else(|| format!("expected a list of strings, found {item}"))
                })
                .collect(),
            toml::Value::String(s) => Ok(s
                .split(',')
                .map(str::trim)
                .filter(|s| !s.is_empty())
                .map(str::to_owned)
                .collect()),
            _ => Err(format!("expected a list of strings, found {value}")),
        }
    }
    fn to_toml(&self) -> toml::Value {
        toml::Value::Array(self.iter().cloned().map(toml::Value::String).collect())
    }
}

/// How hidden blocks are kept from clients (`anticheat.anti-xray.engine-mode`).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Default)]
pub enum AntiXrayMode {
    /// Clients get the real blocks (Vanilla).
    #[default]
    Disabled,
    /// Hidden blocks that touch no transparent block are sent as the dimension's base stone.
    Hide,
    /// Hidden and replacement blocks that touch no transparent block are sent as random hidden
    /// blocks, so the client sees fake ores everywhere.
    Obfuscate,
}

impl RuleValue for AntiXrayMode {
    const SHAPE: ValueShape = ValueShape::one_of(&["disabled", "hide", "obfuscate"]);
    fn from_toml(value: &toml::Value) -> Result<Self, String> {
        match value {
            toml::Value::Boolean(false) => Ok(AntiXrayMode::Disabled),
            toml::Value::String(s) => match s.trim().to_ascii_lowercase().as_str() {
                "disabled" => Ok(AntiXrayMode::Disabled),
                "hide" => Ok(AntiXrayMode::Hide),
                "obfuscate" => Ok(AntiXrayMode::Obfuscate),
                _ => Err(format!(
                    "expected \"disabled\", \"hide\" or \"obfuscate\", found {value}"
                )),
            },
            _ => Err(format!(
                "expected \"disabled\", \"hide\" or \"obfuscate\", found {value}"
            )),
        }
    }
    fn to_toml(&self) -> toml::Value {
        let name = match self {
            AntiXrayMode::Disabled => "disabled",
            AntiXrayMode::Hide => "hide",
            AntiXrayMode::Obfuscate => "obfuscate",
        };
        toml::Value::String(name.to_owned())
    }
}

/// A value that is either switched off (written `"disabled"` or `false`) or set.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Default)]
pub enum DisabledOr<T> {
    /// Switched off.
    #[default]
    Disabled,
    /// Switched on with this value.
    Value(T),
}

impl<T: Copy> DisabledOr<T> {
    /// The value, or `None` when disabled.
    pub fn get(self) -> Option<T> {
        match self {
            DisabledOr::Disabled => None,
            DisabledOr::Value(v) => Some(v),
        }
    }
}

impl<T: RuleValue> RuleValue for DisabledOr<T> {
    const SHAPE: ValueShape = ValueShape {
        ty: T::SHAPE.ty,
        keyword: Some("disabled"),
        choices: &[],
    };
    fn from_toml(value: &toml::Value) -> Result<Self, String> {
        match value {
            toml::Value::Boolean(false) => Ok(DisabledOr::Disabled),
            toml::Value::String(s) if s.eq_ignore_ascii_case("disabled") => {
                Ok(DisabledOr::Disabled)
            }
            _ => T::from_toml(value)
                .map(DisabledOr::Value)
                .map_err(|e| format!("{e} (or \"disabled\")")),
        }
    }
    fn to_toml(&self) -> toml::Value {
        match self {
            DisabledOr::Disabled => toml::Value::String("disabled".to_owned()),
            DisabledOr::Value(v) => v.to_toml(),
        }
    }
    fn numeric(&self) -> Option<f64> {
        match self {
            DisabledOr::Disabled => None,
            DisabledOr::Value(v) => v.numeric(),
        }
    }
}

/// Declares a rule set: a struct of groups, each a struct of rules, with per-profile defaults,
/// optional ranges, TOML access by dotted key and the [`RuleInfo`] table for documentation.
/// Adding a setting is one declaration:
///
/// ```ignore
/// rules! {
///     /// Rules of one world.
///     pub struct WorldRules {
///         /// Chunk loading.
///         chunks: ChunkRules = "performance.chunks" {
///             /// Chunks sent to one player per tick.
///             send_rate: u32 = "send-rate", Performance, range = [1, 1024],
///                 vanilla = 16, paper = 8;
///             /// Worker threads; read once at startup.
///             threads: u16 = "threads", Setting, restart = true, vanilla = 0;
///         }
///     }
/// }
/// ```
///
/// The TOML key of a rule is `<group key>.<key>`; hot paths read plain fields
/// (`rules.chunks.send_rate`). Profiles not given take the `vanilla` value (also
/// `performance`: it never inherits `paper`), except `crowd`, which takes the `performance`
/// value. `range` bounds
/// numeric values (inclusive, checked on load); `restart = true` marks rules that are read only at
/// startup, all others are hot-reloadable.
#[macro_export]
macro_rules! rules {
    (
        $(#[doc = $sdoc:literal])*
        $vis:vis struct $name:ident {
            $(
                $(#[doc = $gdoc:literal])*
                $group:ident: $gty:ident = $gkey:literal {
                    $(
                        $(#[doc = $doc:literal])*
                        $field:ident: $ty:ty = $key:literal, $kind:ident
                            $(, range = [$min:expr, $max:expr])?
                            $(, restart = $restart:literal)?
                            , vanilla = $vanilla:expr
                            $(, technical = $technical:expr)?
                            $(, paper = $paper:expr)?
                            $(, spigot = $spigot:expr)?
                            $(, performance = $performance:expr)?
                            $(, crowd = $crowd:expr)?
                        ;
                    )*
                }
            )*
        }
    ) => {
        $(#[doc = $sdoc])*
        #[derive(Clone, Debug, PartialEq)]
        $vis struct $name {
            $(
                $(#[doc = $gdoc])*
                pub $group: $gty,
            )*
        }

        $(
            $(#[doc = $gdoc])*
            #[derive(Clone, Debug, PartialEq)]
            $vis struct $gty {
                $(
                    $(#[doc = $doc])*
                    pub $field: $ty,
                )*
            }
        )*

        impl $crate::RuleSet for $name {
            const RULES: &'static [$crate::RuleInfo] = &[
                $($(
                    $crate::RuleInfo {
                        key: concat!($gkey, ".", $key),
                        group: $gkey,
                        name: $key,
                        kind: $crate::Kind::$kind,
                        value: <$ty as $crate::RuleValue>::SHAPE,
                        range: $crate::__rules_pick!($(Some(($min as f64, $max as f64)))? ; None),
                        restart: $crate::__rules_pick!($($restart)? ; false),
                        doc: concat!($($doc, "\n",)*),
                    },
                )*)*
            ];

            fn for_profile(profile: $crate::Profile) -> Self {
                Self {
                    $(
                        $group: $gty {
                            $(
                                $field: match profile {
                                    $crate::Profile::Vanilla => $vanilla,
                                    $crate::Profile::Technical =>
                                        $crate::__rules_pick!($($technical)? ; $vanilla),
                                    $crate::Profile::Paper =>
                                        $crate::__rules_pick!($($paper)? ; $vanilla),
                                    $crate::Profile::Spigot =>
                                        $crate::__rules_pick!($($spigot)? ; $vanilla),
                                    $crate::Profile::Performance =>
                                        $crate::__rules_pick!($($performance)? ; $vanilla),
                                    $crate::Profile::Crowd => $crate::__rules_pick!(
                                        $($crowd)? ;
                                        $crate::__rules_pick!($($performance)? ; $vanilla)
                                    ),
                                },
                            )*
                        },
                    )*
                }
            }

            fn set(&mut self, key: &str, value: &$crate::toml::Value) -> Result<bool, String> {
                let mut index = 0;
                $($(
                    if key == Self::RULES[index].key {
                        let parsed: $ty = $crate::RuleValue::from_toml(value)?;
                        Self::RULES[index].check_range($crate::RuleValue::numeric(&parsed))?;
                        self.$group.$field = parsed;
                        return Ok(true);
                    }
                    index += 1;
                )*)*
                let _ = index;
                Ok(false)
            }

            fn get(&self, key: &str) -> Option<$crate::toml::Value> {
                $($(
                    if key == concat!($gkey, ".", $key) {
                        return Some($crate::RuleValue::to_toml(&self.$group.$field));
                    }
                )*)*
                None
            }
        }
    };
}

/// Picks a profile value or falls back to the `vanilla` value. Internal to [`rules!`](crate::rules).
#[doc(hidden)]
#[macro_export]
macro_rules! __rules_pick {
    (; $default:expr) => {
        $default
    };
    ($value:expr ; $default:expr) => {
        $value
    };
}
