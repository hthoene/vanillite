//! Rule types: kinds, profiles, value types and the [`rules!`](crate::rules) catalogue macro.

use std::fmt;

/// What a rule is about. Decides how a deviation from Vanilla is judged.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Kind {
    /// Fixes a real security hole (crash, privilege escalation, resource exhaustion). Always on;
    /// only its limits are tunable.
    Security,
    /// A deterministic Vanilla mechanic that is commonly called an exploit (TNT duplication,
    /// headless pistons, …). Vanilla behaviour by default (decision D1).
    Exploit,
    /// A fix of a Vanilla bug that is not a security hole.
    Fix,
    /// A gameplay tunable (growth rates, despawn ranges, …).
    Gameplay,
    /// A performance deviation that changes observable behaviour (activation range, caps, …).
    Performance,
    /// A limit that Vanilla does not have but that does not change normal play.
    Limit,
    /// An operational setting without any effect on game behaviour (thread counts, watchdog).
    Setting,
}

/// A preset of rule values. The file selects one and overrides single keys.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Default)]
pub enum Profile {
    /// Vanilla behaviour, as exact as possible. Deviates only for security.
    Vanilla,
    /// Vanilla plus what technical players need.
    Technical,
    /// Paper's defaults (the default, #319): behaves like a default Paper server.
    #[default]
    Paper,
    /// Spigot's defaults.
    Spigot,
    /// Vanillite's strongest optimizations that change Vanilla behaviour only a little
    /// (activation range, merge radii, spawn and despawn tuning, overload protection, ...).
    Performance,
    /// `performance` plus crowd mode (`performance.crowd`): far players move less smoothly and
    /// each player sees only the nearest players, so thousands fit into one place.
    Crowd,
}

impl Profile {
    /// All profiles, in documentation order.
    pub const ALL: [Profile; 6] = [
        Profile::Vanilla,
        Profile::Technical,
        Profile::Paper,
        Profile::Spigot,
        Profile::Performance,
        Profile::Crowd,
    ];

    /// The name used in `vanillite.toml`.
    pub fn name(self) -> &'static str {
        match self {
            Profile::Vanilla => "vanilla",
            Profile::Technical => "technical",
            Profile::Paper => "paper",
            Profile::Spigot => "spigot",
            Profile::Performance => "performance",
            Profile::Crowd => "crowd",
        }
    }

    /// One line on how the profile behaves, for the startup log.
    pub fn summary(self) -> &'static str {
        match self {
            Profile::Vanilla => "reproduces Vanilla behaviour as exactly as possible",
            Profile::Technical => "Vanilla plus what technical players need",
            Profile::Paper => "behaves like a default Paper server",
            Profile::Spigot => "behaves like a default Spigot server",
            Profile::Performance => {
                "Vanillite's strongest optimizations, deviates a little from Vanilla"
            }
            Profile::Crowd => "performance plus crowd mode: thousands of players in one place",
        }
    }

    /// Parses a profile name (case-insensitive).
    pub fn parse(name: &str) -> Option<Profile> {
        Profile::ALL
            .into_iter()
            .find(|p| p.name().eq_ignore_ascii_case(name.trim()))
    }
}

impl fmt::Display for Profile {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.name())
    }
}

/// The type of a rule's value.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ValueType {
    /// `true` or `false`.
    Bool,
    /// An integer.
    Integer,
    /// A number, integer or decimal.
    Number,
    /// A string.
    Text,
}

/// The accepted form of a rule's value, for documentation and generated configuration panels.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct ValueShape {
    /// The type of a set value.
    pub ty: ValueType,
    /// A word accepted instead of a value (`vanilla`, `disabled`).
    pub keyword: Option<&'static str>,
    /// The complete set of accepted values, if it is fixed (enumerations); empty otherwise.
    pub choices: &'static [&'static str],
}

impl ValueShape {
    const fn of(ty: ValueType) -> ValueShape {
        ValueShape {
            ty,
            keyword: None,
            choices: &[],
        }
    }

    const fn one_of(choices: &'static [&'static str]) -> ValueShape {
        ValueShape {
            ty: ValueType::Text,
            keyword: None,
            choices,
        }
    }
}

/// Static description of one rule, generated by [`rules!`](crate::rules).
#[derive(Clone, Copy, Debug)]
pub struct RuleInfo {
    /// Full dotted TOML key, e.g. `performance.threads.compute`.
    pub key: &'static str,
    /// The TOML table of the rule, e.g. `performance.threads`.
    pub group: &'static str,
    /// The key inside its table, e.g. `compute`.
    pub name: &'static str,
    /// What the rule is about.
    pub kind: Kind,
    /// The accepted form of the value.
    pub value: ValueShape,
    /// Inclusive range of numeric values, if the rule has one.
    pub range: Option<(f64, f64)>,
    /// A change only takes effect after a restart; all other rules are hot-reloadable.
    pub restart: bool,
    /// The documentation comment of the rule, one line per doc line.
    pub doc: &'static str,
}

impl RuleInfo {
    /// Checks a value against the rule's range.
    pub fn check_range(&self, value: Option<f64>) -> Result<(), String> {
        match (self.range, value) {
            (Some((min, max)), Some(v)) if v < min || v > max => {
                Err(format!("{v} is out of range ({min}..={max})"))
            }
            _ => Ok(()),
        }
    }
}

/// A rule set generated by [`rules!`](crate::rules).
pub trait RuleSet: Clone + fmt::Debug + Send + Sync + 'static {
    /// Every rule of the set, in declaration order.
    const RULES: &'static [RuleInfo];

    /// The values of a profile.
    fn for_profile(profile: Profile) -> Self;

    /// Sets one rule by its dotted key. `Ok(false)` if the key is not part of this set.
    fn set(&mut self, key: &str, value: &toml::Value) -> Result<bool, String>;

    /// The current value of one rule by its dotted key.
    fn get(&self, key: &str) -> Option<toml::Value>;
}

/// A type that can be the value of a rule.
pub trait RuleValue: Sized {
    /// The accepted form of the value.
    const SHAPE: ValueShape;
    /// Parses the value from TOML.
    fn from_toml(value: &toml::Value) -> Result<Self, String>;
    /// Renders the value as TOML.
    fn to_toml(&self) -> toml::Value;
    /// The number to check against a rule's range, if the value is numeric.
    fn numeric(&self) -> Option<f64> {
        None
    }
}

impl RuleValue for bool {
    const SHAPE: ValueShape = ValueShape::of(ValueType::Bool);
    fn from_toml(value: &toml::Value) -> Result<Self, String> {
        value
            .as_bool()
            .ok_or_else(|| format!("expected true or false, found {value}"))
    }
    fn to_toml(&self) -> toml::Value {
        toml::Value::Boolean(*self)
    }
}

macro_rules! integer_rule_value {
    ($($ty:ty),*) => {$(
        impl RuleValue for $ty {
            const SHAPE: ValueShape = ValueShape::of(ValueType::Integer);
            fn from_toml(value: &toml::Value) -> Result<Self, String> {
                let raw = value
                    .as_integer()
                    .ok_or_else(|| format!("expected an integer, found {value}"))?;
                <$ty>::try_from(raw).map_err(|_| {
                    format!("{raw} is out of range ({}..={})", <$ty>::MIN, <$ty>::MAX)
                })
            }
            fn to_toml(&self) -> toml::Value {
                toml::Value::Integer(i64::from(*self))
            }
            fn numeric(&self) -> Option<f64> {
                Some(*self as f64)
            }
        }
    )*};
}
integer_rule_value!(u8, u16, u32, i8, i16, i32, i64);

impl RuleValue for f64 {
    const SHAPE: ValueShape = ValueShape::of(ValueType::Number);
    fn from_toml(value: &toml::Value) -> Result<Self, String> {
        match value {
            toml::Value::Float(f) => Ok(*f),
            toml::Value::Integer(i) => Ok(*i as f64),
            _ => Err(format!("expected a number, found {value}")),
        }
    }
    fn to_toml(&self) -> toml::Value {
        toml::Value::Float(*self)
    }
    fn numeric(&self) -> Option<f64> {
        Some(*self)
    }
}

impl RuleValue for String {
    const SHAPE: ValueShape = ValueShape::of(ValueType::Text);
    fn from_toml(value: &toml::Value) -> Result<Self, String> {
        value
            .as_str()
            .map(str::to_owned)
            .ok_or_else(|| format!("expected a string, found {value}"))
    }
    fn to_toml(&self) -> toml::Value {
        toml::Value::String(self.clone())
    }
}

/// A value that is either Vanilla's (written `"vanilla"`) or a custom one. Keeps Vanilla's
/// numbers out of config files and out of the catalogue.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Default)]
pub enum VanillaOr<T> {
    /// Vanilla's behaviour.
    #[default]
    Vanilla,
    /// A custom value.
    Value(T),
}

impl<T: Copy> VanillaOr<T> {
    /// The custom value, or `vanilla` for Vanilla's.
    pub fn or(self, vanilla: T) -> T {
        match self {
            VanillaOr::Vanilla => vanilla,
            VanillaOr::Value(v) => v,
        }
    }

    /// `vanilla` for Vanilla's value, else the custom value mapped by `f`.
    pub fn map_or<U>(self, vanilla: U, f: impl FnOnce(T) -> U) -> U {
        match self {
            VanillaOr::Vanilla => vanilla,
            VanillaOr::Value(v) => f(v),
        }
    }

    /// The custom value, `None` for Vanilla's.
    pub fn map<U>(self, f: impl FnOnce(T) -> U) -> Option<U> {
        match self {
            VanillaOr::Vanilla => None,
            VanillaOr::Value(v) => Some(f(v)),
        }
    }
}

impl<T: RuleValue> RuleValue for VanillaOr<T> {
    const SHAPE: ValueShape = ValueShape {
        ty: T::SHAPE.ty,
        keyword: Some("vanilla"),
        choices: &[],
    };
    fn from_toml(value: &toml::Value) -> Result<Self, String> {
        match value.as_str() {
            Some(s) if s.eq_ignore_ascii_case("vanilla") => Ok(VanillaOr::Vanilla),
            _ => T::from_toml(value)
                .map(VanillaOr::Value)
                .map_err(|e| format!("{e} (or \"vanilla\")")),
        }
    }
    fn to_toml(&self) -> toml::Value {
        match self {
            VanillaOr::Vanilla => toml::Value::String("vanilla".to_owned()),
            VanillaOr::Value(v) => v.to_toml(),
        }
    }
    fn numeric(&self) -> Option<f64> {
        match self {
            VanillaOr::Vanilla => None,
            VanillaOr::Value(v) => v.numeric(),
        }
    }
}

