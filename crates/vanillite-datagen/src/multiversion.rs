//! The adapter tables of the multi-version layer (`vanillite-multiversion`, architecture 14.3):
//! each kept older version (`data/multiversion/<id>/version.toml` pins it, [`crate::keep`]
//! extracts its facts) and its successor (the next kept version, or the current one) become the
//! tables of one adapter step.

