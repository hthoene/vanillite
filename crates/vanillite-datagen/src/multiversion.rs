/// A version's facts, from its extracted data.
struct Facts {
    id: String,
    protocol: i64,
    packets: Value,
    registries: Value,
    blocks: Vec<Block>,
    /// Entity type name → facts that must match for a fallback.
    entities: HashMap<String, String>,
    synchronized: Option<Value>,
    /// `entity_data.json`: serializers and per entity type its data items.
    entity_data: Option<Value>,
    /// `packet_fields.json`: the Java shape of every packet.
    packet_fields: Option<Value>,
}

struct Block {
    name: String,
    first_state: usize,
    default_state: usize,
    properties: Vec<(String, Vec<String>)>,
}

impl Block {
    fn state_count(&self) -> usize {
        self.properties.iter().map(|p| p.1.len()).product()
    }

    /// Property values of a state of this block.
    fn values(&self, state: usize) -> Vec<&str> {
        let mut stride = self.state_count();
        let offset = state - self.first_state;
        self.properties
            .iter()
            .map(|(_, values)| {
                stride /= values.len();
                values
                    .get(offset / stride % values.len())
                    .map_or("", String::as_str)
            })
            .collect()
    }
}

impl Facts {
    fn load(dir: &Path) -> Result<Self> {
        let version: toml::Table = read(&dir.join("version.toml"))?
            .parse()
            .map_err(|e| format!("{}: {e}", dir.display()))?;
        let mut blocks = Vec::new();
        for b in read_json(&dir.join("blocks.json"))?
            .as_array()
            .ok_or("blocks.json: expected an array")?
        {
            let usize_of = |k: &str| {
                b[k].as_u64()
                    .and_then(|v| usize::try_from(v).ok())
                    .ok_or_else(|| format!("blocks.json: {k} missing"))
            };
            let properties = b["properties"]
                .as_array()
                .map(|ps| {
                    ps.iter()
                        .map(|p| {
                            (
                                p["name"].as_str().unwrap_or_default().to_owned(),
                                p["values"]
                                    .as_array()
                                    .map(|vs| {
                                        vs.iter()
                                            .map(|v| v.as_str().unwrap_or_default().to_owned())
                                            .collect()
                                    })
                                    .unwrap_or_default(),
                            )
                        })
                        .collect()
                })
                .unwrap_or_default();
            blocks.push(Block {
                name: b["name"].as_str().unwrap_or_default().to_owned(),
                first_state: usize_of("first_state")?,
                default_state: usize_of("default_state")?,
                properties,
            });
        }
        let mut entities = HashMap::new();
        for e in read_json(&dir.join("entities.json"))?
            .as_array()
            .ok_or("entities.json: expected an array")?
        {
            let facts: Vec<String> = ENTITY_FACTS
                .iter()
                .skip(1)
                .map(|k| e[*k].to_string())
                .collect();
            entities.insert(
                e["name"].as_str().unwrap_or_default().to_owned(),
                facts.join(" "),
            );
        }
        let optional = |f: &str| {
            let path = dir.join(f);
            path.exists().then(|| read_json(&path)).transpose()
        };
        let entity_data = optional("entity_data.json")?;
        let packet_fields = optional("packet_fields.json")?;
        let synchronized = dir
            .join("synchronized.json")
            .exists()
            .then(|| read_json(&dir.join("synchronized.json")))
            .transpose()?;
        Ok(Self {
            id: version
                .get("id")
                .and_then(|v| v.as_str())
                .ok_or("version.toml: no id")?
                .to_owned(),
            protocol: version
                .get("protocol")
                .and_then(toml::Value::as_integer)
                .ok_or("version.toml: no protocol")?,
            packets: read_json(&dir.join("packets.json"))?,
            registries: read_json(&dir.join("registries.json"))?,
            blocks,
            entities,
            synchronized,
            entity_data,
            packet_fields,
        })
    }

    fn entries(&self, registry: &str) -> Vec<String> {
        self.registries[registry]["entries"]
            .as_array()
            .map(|a| {
                a.iter()
                    .map(|e| e.as_str().unwrap_or_default().to_owned())
                    .collect()
            })
            .unwrap_or_default()
    }
}

/// The generated files of `vanillite-multiversion` (`mod.rs` and one module per step) from the
/// data of the current version and of the kept versions.
pub fn generate(current: &Path, kept_dirs: &[PathBuf]) -> Result<Vec<(String, String)>> {
    let mut kept: Vec<Facts> = Vec::new();
    for d in kept_dirs {
        kept.push(Facts::load(d)?);
    }
    let current = Facts::load(current)?;
    kept.retain(|f| f.protocol < current.protocol);
    kept.sort_by_key(|f| f.protocol);

    // Every configuration and play packet of all versions, by direction: the packet kinds the
    // step code matches on.
    let kinds = |dir: &str| -> Vec<String> {
        let mut set = BTreeSet::new();
        for f in kept.iter().chain(std::iter::once(&current)) {
            for state in ["configuration", "play"] {
                for n in f.packets[state][dir].as_array().into_iter().flatten() {
                    set.insert(n.as_str().unwrap_or_default().to_owned());
                }
            }
        }
        set.into_iter().collect()
    };
    let (cb, sb) = (kinds("clientbound"), kinds("serverbound"));

    let mut files = Vec::new();
    let mut module = String::from(HEADER);
    module.push_str(
        "//! Tables of the adapter steps, one module per kept version: ids of that version and of\n\
         //! its successor.\n\n",
    );
    for (i, old) in kept.iter().enumerate() {
        let new = kept.get(i + 1).unwrap_or(&current);
        let name = module_name(&old.id);
        let _ = writeln!(module, "pub mod {name};");
        files.push((format!("{name}.rs"), step(old, new, &cb, &sb)?));
    }
    for (name, list, what) in [("Cb", &cb, "clientbound"), ("Sb", &sb, "serverbound")] {
        let _ = writeln!(
            module,
            "\n/// Every {what} configuration and play packet of the kept versions and the current one.\n\
             #[derive(Debug, Clone, Copy, PartialEq, Eq)]\npub enum {name} {{"
        );
        for n in list {
            let _ = writeln!(module, "    {},", camel(n));
        }
        module.push_str("}\n");
    }
    files.push(("mod.rs".to_owned(), module));
    Ok(files)
}

/// `26.2` → `v26_2`.
fn module_name(id: &str) -> String {
    let mut s = String::from("v");
    s.extend(
        id.chars()
            .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' }),
    );
    s
}

fn step(old: &Facts, new: &Facts, cb: &[String], sb: &[String]) -> Result<String> {
    let mut o = String::from(HEADER);
    let _ = writeln!(
        o,
        "//! Minecraft {} (protocol {}) ↔ {} (protocol {}).\n\n\
         use super::{{Cb, Sb}};\n\
         use crate::table::{{PacketTable, Remap}};\n\n\
         /// Version name of the older side.\npub const ID: &str = {:?};\n\
         /// Protocol version of the older side.\npub const PROTOCOL: i32 = {};\n\
         /// Version name of the newer side.\npub const NEXT_ID: &str = {:?};\n\
         /// Protocol version of the newer side.\npub const NEXT_PROTOCOL: i32 = {};\n",
        old.id, old.protocol, new.id, new.protocol, old.id, old.protocol, new.id, new.protocol
    );

    // Packets: by name per state and direction.
    for (state, dir) in [
        ("login", "clientbound"),
        ("login", "serverbound"),
        ("configuration", "clientbound"),
        ("configuration", "serverbound"),
        ("play", "clientbound"),
        ("play", "serverbound"),
    ] {
        let names = |f: &Facts| -> Vec<String> {
            f.packets[state][dir]
                .as_array()
                .map(|a| {
                    a.iter()
                        .map(|e| e.as_str().unwrap_or_default().to_owned())
                        .collect()
                })
                .unwrap_or_default()
        };
        let (o_names, n_names) = (names(old), names(new));
        let remap = remap_by_name(&o_names, &n_names, |_| None);
        let _ = writeln!(
            o,
            "/// `{state}` packets, {dir}.\npub static {}_{}: PacketTable = PacketTable {{",
            state.to_ascii_uppercase(),
            dir.to_ascii_uppercase()
        );
        write_ids(&mut o, "to_old", &remap.0);
        write_ids(&mut o, "to_new", &remap.1);
        o.push_str("};\n\n");
        // Packets in both versions whose Java shape changed: the step must rewrite them (by
        // the newer id clientbound, the older id serverbound), else they are dropped.
        let changed: Vec<usize> = match (&old.packet_fields, &new.packet_fields) {
            (Some(of), Some(nf)) => {
                let flow = if dir == "clientbound" {
                    &n_names
                } else {
                    &o_names
                };
                flow.iter()
                    .enumerate()
                    .filter(|(_, name)| {
                        let key = format!("{dir}/{name}");
                        let (a, b) = (&of[&key]["fields"], &nf[&key]["fields"]);
                        // `ResourceLocation` was renamed `Identifier` (1.21.11), same codec.
                        let shape =
                            |v: &Value| v.to_string().replace("ResourceLocation", "Identifier");
                        !a.is_null() && !b.is_null() && shape(a) != shape(b)
                    })
                    .map(|(i, _)| i)
                    .collect()
            }
            _ => Vec::new(),
        };
        let _ = writeln!(
            o,
            "/// `{state}` {dir} packets whose shape changed ({} ids).\npub static {}_{}_CHANGED: &[i32] = &{changed:?};\n",
            if dir == "clientbound" {
                "newer"
            } else {
                "older"
            },
            state.to_ascii_uppercase(),
            dir.to_ascii_uppercase()
        );
        for (side, list) in [("old", &o_names), ("new", &n_names)] {
            let _ = writeln!(
                o,
                "/// Ids of the `{state}` {dir} packets of the {} version.\npub mod {side}_{state}_{dir} {{",
                if side == "old" { "older" } else { "newer" }
            );
            for (i, n) in list.iter().enumerate() {
                let _ = writeln!(o, "    pub const {}: i32 = {i};", const_name(n));
            }
            o.push_str("}\n\n");
        }
    }

    // Packet kinds by id, ids by kind.
    let mut kinds = String::new();
    for (state, dir, side, all, enum_name) in [
        ("configuration", "clientbound", new, cb, "Cb"),
        ("play", "clientbound", new, cb, "Cb"),
        ("configuration", "serverbound", old, sb, "Sb"),
        ("play", "serverbound", old, sb, "Sb"),
    ] {
        let list: Vec<String> = side.packets[state][dir]
            .as_array()
            .into_iter()
            .flatten()
            .map(|n| format!("{enum_name}::{}", camel(n.as_str().unwrap_or_default())))
            .collect();
        let _ = writeln!(kinds, "    {state}_{dir}: &[{}],", list.join(", "));
        // The other side's ids by kind (-1: absent).
        let other = if dir == "clientbound" { old } else { new };
        let names: Vec<&str> = other.packets[state][dir]
            .as_array()
            .into_iter()
            .flatten()
            .filter_map(Value::as_str)
            .collect();
        let ids: Vec<String> = all
            .iter()
            .map(|k| {
                names
                    .iter()
                    .position(|n| n == k)
                    .map_or_else(|| "-1".to_owned(), |i| i.to_string())
            })
            .collect();
        let _ = writeln!(
            kinds,
            "    {}_{state}_{dir}: &[{}],",
            if dir == "clientbound" { "old" } else { "new" },
            ids.join(", ")
        );
    }

    // Static registries that differ.
    let mut tables = Vec::new();
    let mut entity_type_to_old: Option<Vec<Option<usize>>> = None;
    for registry in NETWORK_REGISTRIES {
        let (oe, ne) = (old.entries(registry), new.entries(registry));
        if oe == ne || oe.is_empty() || ne.is_empty() {
            continue;
        }
        let remap = remap_by_name(&oe, &ne, |name| {
            if SIMILAR.contains(registry) {
                // Blocks and items without a similar older one show as stone.
                let stand_in = stand_ins(name)
                    .iter()
                    .find_map(|s| oe.iter().position(|o| o == s));
                stand_in
                    .or_else(|| similar(name, &oe))
                    .or_else(|| oe.iter().position(|e| e == "minecraft:stone"))
            } else if *registry == "minecraft:entity_type" {
                let facts = new.entities.get(name)?;
                let same: Vec<String> = oe
                    .iter()
                    .filter(|o| old.entities.get(*o) == Some(facts))
                    .cloned()
                    .collect();
                similar(name, &same)
                    .and_then(|i| oe.iter().position(|o| Some(o) == same.get(i)))
                    .or_else(|| {
                        let (_, stand_ins) = ENTITY_STAND_INS.iter().find(|(n, _)| *n == name)?;
                        stand_ins
                            .iter()
                            .find_map(|s| oe.iter().position(|o| o == s))
                    })
            } else {
                None
            }
        });
        let _ = writeln!(
            o,
            "/// `{registry}` ids ({} → {} entries).\npub static {}: Remap = Remap {{",
            oe.len(),
            ne.len(),
            const_name(registry)
        );
        write_ids(&mut o, "to_old", &remap.0);
        write_ids(&mut o, "to_new", &remap.1);
        o.push_str("};\n\n");
        tables.push((*registry, const_name(registry)));
        if *registry == "minecraft:entity_type" {
            entity_type_to_old = Some(remap.0.clone());
        }
        // Names of the newer entries without an exact counterpart (sounds go inline by name).
        let missing: Vec<(usize, &String)> = ne
            .iter()
            .enumerate()
            .filter(|(_, n)| !oe.contains(n))
            .collect();
        let _ = writeln!(
            o,
            "/// Newer `{registry}` entries the older version does not have.\npub static {}_ADDED: &[(u16, &str)] = &[",
            const_name(registry)
        );
        for (i, n) in missing {
            let _ = writeln!(o, "    ({i}, {n:?}),");
        }
        o.push_str("];\n\n");
    }

    o.push_str(
        "/// The table of a static registry whose ids differ; `None` if they are the same.\n\
         pub fn remap(registry: &str) -> Option<&'static Remap> {\n    Some(match registry {\n",
    );
    for (registry, table) in &tables {
        let _ = writeln!(o, "        {registry:?} => &{table},");
    }
    o.push_str("        _ => return None,\n    })\n}\n\n");

    let has_entity_data = entity_data(&mut o, old, new, entity_type_to_old.as_ref())?;

    // Block states.
    let states = block_states(old, new);
    let _ = writeln!(
        o,
        "/// Block state ids: newer state → older state (same block and property values, or the\n\
         /// closest block), older → newer.\npub static BLOCK_STATE: Remap = Remap {{"
    );
    write_ids(&mut o, "to_old", &states.0);
    write_ids(&mut o, "to_new", &states.1);
    o.push_str("};\n\n");

    // Synchronised registries the older version knows.
    let sync = old
        .synchronized
        .as_ref()
        .ok_or_else(|| format!("{}: synchronized.json missing", old.id))?;
    o.push_str(
        "/// Entries of the synchronised data-driven registries that the older version has built\n\
         /// in, sorted. Registries it does not know are left out.\n\
         pub static SYNCHRONIZED: &[(&str, &[&str])] = &[\n",
    );
    for (registry, entries) in sync
        .as_object()
        .ok_or("synchronized.json: expected an object")?
    {
        let entries = entries.as_array().cloned().unwrap_or_default();
        let _ = writeln!(o, "    ({registry:?}, &[");
        for e in entries {
            let _ = writeln!(o, "        {e},");
        }
        o.push_str("    ]),\n");
    }
    o.push_str("];\n\n");

    // Static registries of the older version (tags of other registries are not sent to it).
    o.push_str("/// Static registries the older version has.\npub static STATIC_REGISTRIES: &[&str] = &[\n");
    if let Some(regs) = old.registries.as_object() {
        for name in regs.keys() {
            let _ = writeln!(o, "    {name:?},");
        }
    }
    o.push_str("];\n\n");

    // Names of the newer version's entries where the codec depends on the entry (particle
    // options, argument parser properties, stat values) or the entry is special.
    for (registry, name) in [
        ("minecraft:particle_type", "NEW_PARTICLE_TYPES"),
        (
            "minecraft:command_argument_type",
            "NEW_COMMAND_ARGUMENT_TYPES",
        ),
        ("minecraft:stat_type", "NEW_STAT_TYPES"),
        ("minecraft:entity_type", "NEW_ENTITY_TYPES"),
        ("minecraft:data_component_type", "NEW_DATA_COMPONENT_TYPES"),
    ] {
        let _ = writeln!(
            o,
            "\n/// `{registry}` names of the newer version by id.\npub static {name}: &[&str] = &["
        );
        for e in new.entries(registry) {
            let _ = writeln!(o, "    {e:?},");
        }
        o.push_str("];\n");
    }
    // Single entries the hand-written step code refers to, by name on both sides (-1: absent).
    for (registry, name) in NAMED {
        let id = |f: &Facts| {
            f.entries(registry)
                .iter()
                .position(|e| e == name)
                .and_then(|i| i64::try_from(i).ok())
                .unwrap_or(-1)
        };
        let c = format!("{}_{}", const_name(registry), const_name(name));
        let _ = writeln!(
            o,
            "\n/// `{name}` in `{registry}`: older and newer id (-1: absent).\n\
             pub const OLD_{c}: i32 = {};\npub const NEW_{c}: i32 = {};",
            id(old),
            id(new)
        );
    }
    let old_string = old
        .entries("minecraft:command_argument_type")
        .iter()
        .position(|e| e == "brigadier:string")
        .unwrap_or(0);
    let _ = writeln!(
        o,
        "\n/// Id of `brigadier:string` in the older version (stands in for unknown parsers).\n\
         pub const OLD_STRING_PARSER: i32 = {old_string};"
    );

    // Enchantments were a static registry before 1.21.
    let _ = writeln!(
        o,
        "\n/// The older version's static enchantment registry (empty if it synchronises them).\n\
         pub static OLD_ENCHANTMENTS: &[&str] = &{:?};",
        old.entries("minecraft:enchantment")
    );

    // Everything above for the step code that works on any step.
    let has = |t: &str| tables.iter().any(|(_, c)| c == t);
    let _ = writeln!(
        o,
        "\n/// The tables above for the step code shared by all steps.\n\
         pub static TABLES: crate::table::Tables = crate::table::Tables {{\n\
         \x20   id: ID,\n    protocol: PROTOCOL,\n    next_id: NEXT_ID,\n    next_protocol: NEXT_PROTOCOL,\n\
         \x20   packets: [&LOGIN_CLIENTBOUND, &LOGIN_SERVERBOUND, &CONFIGURATION_CLIENTBOUND, &CONFIGURATION_SERVERBOUND, &PLAY_CLIENTBOUND, &PLAY_SERVERBOUND],\n\
         \x20   changed: [LOGIN_CLIENTBOUND_CHANGED, LOGIN_SERVERBOUND_CHANGED, CONFIGURATION_CLIENTBOUND_CHANGED, CONFIGURATION_SERVERBOUND_CHANGED, PLAY_CLIENTBOUND_CHANGED, PLAY_SERVERBOUND_CHANGED],\n\
         {kinds}\
         \x20   remap,\n    block_state: &BLOCK_STATE,\n    synchronized: SYNCHRONIZED,\n    static_registries: STATIC_REGISTRIES,\n\
         \x20   new_particle_types: NEW_PARTICLE_TYPES,\n    new_command_argument_types: NEW_COMMAND_ARGUMENT_TYPES,\n\
         \x20   new_stat_types: NEW_STAT_TYPES,\n    new_entity_types: NEW_ENTITY_TYPES,\n\
         \x20   new_data_component_types: NEW_DATA_COMPONENT_TYPES,\n\
         \x20   sound_added: {},\n\
         \x20   old_serializers: {},\n    new_serializers: {},\n    entity_data: {},\n\
         \x20   old_enchantments: OLD_ENCHANTMENTS,\n\
         \x20   old_string_parser: OLD_STRING_PARSER,\n\
         \x20   old_intentionally_empty: OLD_SOUND_EVENT_INTENTIONALLY_EMPTY,\n\
         }};",
        if has("SOUND_EVENT") {
            "SOUND_EVENT_ADDED"
        } else {
            "&[]"
        },
        if has_entity_data {
            "OLD_SERIALIZERS"
        } else {
            "&[]"
        },
        if has_entity_data {
            "NEW_SERIALIZERS"
        } else {
            "&[]"
        },
        if has_entity_data {
            "ENTITY_DATA"
        } else {
            "&[]"
        },
    );
    Ok(o)
}

/// Entity data tables: serializer names on both sides and, per newer entity type, where each
/// of its data items goes in the older version's type (matched by the accessor's class and field
/// name, then by field name and serializer).
fn entity_data(
    o: &mut String,
    old: &Facts,
    new: &Facts,
    type_to_old: Option<&Vec<Option<usize>>>,
) -> Result<bool> {
    let (Some(od), Some(nd)) = (&old.entity_data, &new.entity_data) else {
        return Ok(false);
    };
    let names = |v: &Value| -> Vec<String> {
        v["serializers"]
            .as_array()
            .map(|a| {
                a.iter()
                    .map(|s| s.as_str().unwrap_or_default().to_owned())
                    .collect()
            })
            .unwrap_or_default()
    };
    let (os, ns) = (names(od), names(nd));
    for (side, list) in [("OLD", &os), ("NEW", &ns)] {
        let _ = writeln!(
            o,
            "/// Entity data serializers of the {} version by id.\npub static {side}_SERIALIZERS: &[&str] = &{list:?};\n",
            if side == "OLD" { "older" } else { "newer" }
        );
    }
    let (ot, nt) = (
        old.entries("minecraft:entity_type"),
        new.entries("minecraft:entity_type"),
    );
    o.push_str(
        "/// Entity data per newer entity type id: by newer index, the older index << 8 | older\n\
         /// serializer id (`u16::MAX`: the older type has no such item).\n\
         pub static ENTITY_DATA: &[&[u16]] = &[\n",
    );
    for (i, name) in nt.iter().enumerate() {
        let old_type = match type_to_old {
            Some(t) => t.get(i).copied().flatten().and_then(|j| ot.get(j)),
            None => ot.iter().find(|n| *n == name),
        };
        let items = |d: &Value, t: &str| -> Vec<(u64, String, String)> {
            d["types"][t]
                .as_array()
                .map(|a| {
                    a.iter()
                        .map(|it| {
                            (
                                it[0].as_u64().unwrap_or(0),
                                it[1].as_str().unwrap_or_default().to_owned(),
                                it[2].as_str().unwrap_or_default().to_owned(),
                            )
                        })
                        .collect()
                })
                .unwrap_or_default()
        };
        let new_items = items(nd, name);
        let old_items = old_type.map(|t| items(od, t)).unwrap_or_default();
        let len = new_items.iter().map(|it| it.0 + 1).max().unwrap_or(0);
        let mut map = vec!["u16::MAX".to_owned(); usize::try_from(len).unwrap_or(0)];
        for (index, serializer, field) in &new_items {
            let short = |f: &str| f.rsplit('.').next().unwrap_or(f).to_owned();
            let found = old_items.iter().find(|it| it.2 == *field).or_else(|| {
                old_items
                    .iter()
                    .find(|it| short(&it.2) == short(field) && it.1 == *serializer)
            });
            if let Some((oi, os_name, _)) = found
                && let Some(sid) = os.iter().position(|s| s == os_name)
                && let Some(slot) = usize::try_from(*index).ok().and_then(|i| map.get_mut(i))
            {
                *slot = ((oi << 8) | u64::try_from(sid).unwrap_or(0)).to_string();
            }
        }
        let _ = writeln!(o, "    /* {name} */ &[{}],", map.join(", "));
    }
    o.push_str("];\n\n");
    Ok(true)
}

/// `minecraft:debug/block_value` → `DebugBlockValue`.
fn camel(name: &str) -> String {
    let path = name.strip_prefix("minecraft:").unwrap_or(name);
    let mut out = String::new();
    let mut upper = true;
    for c in path.chars() {
        if c.is_ascii_alphanumeric() {
            out.push(if upper { c.to_ascii_uppercase() } else { c });
            upper = false;
        } else {
            upper = true;
        }
    }
    out
}

/// `u16::MAX` stands for "no counterpart".
fn write_ids(o: &mut String, field: &str, ids: &[Option<usize>]) {
    let values: Vec<String> = ids
        .iter()
        .map(|i| i.map_or_else(|| "u16::MAX".to_owned(), |i| i.to_string()))
        .collect();
    let _ = writeln!(o, "    {field}: &[");
    let mut line = String::from("       ");
    for v in values {
        if line.len() + v.len() + 2 > 100 {
            o.push_str(line.trim_end());
            o.push('\n');
            line = String::from("       ");
        }
        line.push(' ');
        line.push_str(&v);
        line.push(',');
    }
    if !line.trim().is_empty() {
        o.push_str(&line);
        o.push('\n');
    }
    o.push_str("    ],\n");
}

/// Maps by name: newer id → older id (with `fallback` for names the older version lacks) and
/// older id → newer id.
fn remap_by_name(
    old: &[String],
    new: &[String],
    fallback: impl Fn(&str) -> Option<usize>,
) -> (Vec<Option<usize>>, Vec<Option<usize>>) {
    let old_ids: HashMap<&str, usize> = old
        .iter()
        .enumerate()
        .map(|(i, n)| (n.as_str(), i))
        .collect();
    let new_ids: HashMap<&str, usize> = new
        .iter()
        .enumerate()
        .map(|(i, n)| (n.as_str(), i))
        .collect();
    // Renamed entries: by the rename table, then without the attribute prefixes 1.21.2 dropped.
    let renamed = |name: &str, ids: &HashMap<&str, usize>| -> Option<usize> {
        RENAMED
            .iter()
            .find_map(|(a, b)| {
                (*a == name)
                    .then_some(*b)
                    .or_else(|| (*b == name).then_some(*a))
            })
            .and_then(|other| ids.get(other).copied())
            .or_else(|| {
                let bare = unprefixed(name);
                ids.iter()
                    .find(|(k, _)| {
                        k.starts_with("minecraft:") && unprefixed(k) == bare && **k != name
                    })
                    .map(|(_, v)| *v)
                    .filter(|_| name != bare)
                    .or_else(|| {
                        ids.iter()
                            .filter(|(k, _)| unprefixed(k) != **k)
                            .find(|(k, _)| unprefixed(k) == name)
                            .map(|(_, v)| *v)
                    })
            })
    };
    let to_old = new
        .iter()
        .map(|n| {
            old_ids
                .get(n.as_str())
                .copied()
                .or_else(|| renamed(n, &old_ids))
                .or_else(|| fallback(n))
        })
        .collect();
    let to_new = old
        .iter()
        .map(|n| {
            new_ids
                .get(n.as_str())
                .copied()
                .or_else(|| renamed(n, &new_ids))
        })
        .collect();
    (to_old, to_new)
}

/// Entries renamed between versions with the same meaning: (newer, older) names.
const RENAMED: &[(&str, &str)] = &[
    ("minecraft:login_finished", "minecraft:game_profile"),
    ("minecraft:set_held_slot", "minecraft:set_carried_item"),
    ("minecraft:mount_screen_open", "minecraft:horse_screen_open"),
];

/// An attribute name without the `generic.`, `player.` or `zombie.` prefix (1.21.2 dropped
/// them).
fn unprefixed(name: &str) -> String {
    for prefix in [
        "minecraft:generic.",
        "minecraft:player.",
        "minecraft:zombie.",
    ] {
        if let Some(rest) = name.strip_prefix(prefix) {
            return format!("minecraft:{rest}");
        }
    }
    name.to_owned()
}

/// The closest name in `candidates` for a name they lack: the most trailing `_`-separated words
/// in common (`poplar_planks` → `acacia_planks`, `dappled_forest` → `forest`), the shortest and
/// then alphabetically first name on a tie. Same algorithm as `vanillite_multiversion::similar`.
pub fn similar(name: &str, candidates: &[String]) -> Option<usize> {
    let words = |s: &str| -> Vec<String> {
        s.rsplit(':')
            .next()
            .unwrap_or(s)
            .split(['_', '/'])
            .map(str::to_owned)
            .collect()
    };
    let target = words(name);
    let mut best: Option<(usize, usize, &str, usize)> = None;
    for (i, c) in candidates.iter().enumerate() {
        let cw = words(c);
        let common = target
            .iter()
            .rev()
            .zip(cw.iter().rev())
            .take_while(|(a, b)| a == b)
            .count();
        if common == 0 {
            continue;
        }
        let better = match best {
            None => true,
            Some((bc, bl, bn, _)) => {
                common > bc
                    || (common == bc && (c.len() < bl || (c.len() == bl && c.as_str() < bn)))
            }
        };
        if better {
            best = Some((common, c.len(), c.as_str(), i));
        }
    }
    best.map(|b| b.3)
}

/// Block states by block name and property values; states of blocks the older version lacks
/// go to the closest older block (matching property values where it has them).
fn block_states(old: &Facts, new: &Facts) -> (Vec<Option<usize>>, Vec<Option<usize>>) {
    let old_names: Vec<String> = old.blocks.iter().map(|b| b.name.clone()).collect();
    let old_by_name: HashMap<&str, &Block> =
        old.blocks.iter().map(|b| (b.name.as_str(), b)).collect();
    let new_by_name: HashMap<&str, &Block> =
        new.blocks.iter().map(|b| (b.name.as_str(), b)).collect();
    let old_total = old
        .blocks
        .iter()
        .map(|b| b.first_state + b.state_count())
        .max()
        .unwrap_or(0);
    let new_total = new
        .blocks
        .iter()
        .map(|b| b.first_state + b.state_count())
        .max()
        .unwrap_or(0);

    let state_in = |target: &Block, source: &Block, state: usize| -> usize {
        let values = source.values(state);
        let mut id = target.first_state;
        let mut stride = target.state_count();
        let default = target.values(target.default_state);
        for (i, (pname, pvalues)) in target.properties.iter().enumerate() {
            stride /= pvalues.len();
            let wanted = source
                .properties
                .iter()
                .position(|p| &p.0 == pname)
                .and_then(|j| values.get(j).copied())
                .and_then(|v| pvalues.iter().position(|pv| pv == v))
                .or_else(|| {
                    pvalues
                        .iter()
                        .position(|pv| Some(&pv.as_str()) == default.get(i))
                })
                .unwrap_or(0);
            id += wanted * stride;
        }
        id
    };

    let mut to_old = vec![None; new_total];
    for b in &new.blocks {
        // Blocks without a stand-in or a similar older one show as stone.
        let target = old_by_name
            .get(b.name.as_str())
            .copied()
            .or_else(|| {
                stand_ins(&b.name)
                    .iter()
                    .find_map(|s| old_by_name.get(s.as_str()).copied())
            })
            .or_else(|| similar(&b.name, &old_names).and_then(|i| old.blocks.get(i)))
            .or_else(|| old_by_name.get("minecraft:stone").copied());
        for s in b.first_state..b.first_state + b.state_count() {
            if let Some(slot) = to_old.get_mut(s) {
                *slot = Some(target.map_or(0, |t| state_in(t, b, s)));
            }
        }
    }
    let mut to_new = vec![None; old_total];
    for b in &old.blocks {
        let Some(target) = new_by_name.get(b.name.as_str()) else {
            continue;
        };
        for s in b.first_state..b.first_state + b.state_count() {
            if let Some(slot) = to_new.get_mut(s) {
                *slot = Some(state_in(target, b, s));
            }
        }
    }
    (to_old, to_new)
}

/// `minecraft:add_entity` → `ADD_ENTITY`.
fn const_name(name: &str) -> String {
    let path = name.strip_prefix("minecraft:").unwrap_or(name);
    let mut s: String = path
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() {
                c.to_ascii_uppercase()
            } else {
                '_'
            }
        })
        .collect();
    if s.starts_with(|c: char| c.is_ascii_digit()) {
        s.insert(0, '_');
    }
    s
}
