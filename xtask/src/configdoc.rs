//! `cargo xtask config-docs`: the configuration reference `docs/configuration.md`, generated
//! from the typed configuration schema of `vanillite-config` (every `server.properties` key and
//! every `vanillite.toml` rule with its values in each profile), so it never goes stale.
//! `cargo xtask egg` writes it as well and `egg --check` (and its test) checks it.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

use vanillite_config::{
    Kind, Profile, PropertyKind, RuleSet, ServerProperties, ServerRules, ValueType, WorldRules,
    env_name,
};

use crate::Result;

/// The reference, relative to the repository root.
pub const DOC_PATH: &str = "docs/configuration.md";

/// `cargo xtask config-docs [--check]`.
pub fn run(root: &Path, args: &[&str]) -> Result<()> {
    match args {
        [] => {
            crate::write(&root.join(DOC_PATH), &render())?;
            println!("wrote {DOC_PATH}");
            Ok(())
        }
        ["--check"] => check(root),
        _ => Err(crate::USAGE.to_owned()),
    }
}

/// Fails if the committed reference differs from the generated one.
pub fn check(root: &Path) -> Result<()> {
    let committed = crate::read(&root.join(DOC_PATH)).unwrap_or_default();
    if committed != render() {
        return Err(format!(
            "{DOC_PATH} is out of date with the configuration schema; run `cargo xtask config-docs`"
        ));
    }
    Ok(())
}

/// The reference as Markdown.
pub fn render() -> String {
    let mut out = String::from(
        "# Configuration reference\n\n\
         <!-- Generated by `cargo xtask config-docs` from crates/vanillite-config. Do not edit. -->\n\n\
         Vanillite reads two files from the server directory, both created with every key on \
         the first start:\n\n\
         - [`server.properties`](#serverproperties): Vanilla's keys with Vanilla's meaning and \
         defaults. Unknown keys are kept.\n\
         - [`vanillite.toml`](#vanillitetoml): everything Vanillite-specific: the `profile` and \
         the rules below. Every rule is written commented out with its documentation; \
         uncomment a key to override the profile.\n\n\
         Every key of both files can also be set with an environment variable for one run \
         (it is not written to the files): `VANILLITE_` plus the key in upper case, `-` \
         becomes `_` and `.` becomes `__`, e.g. `VANILLITE_MAX_PLAYERS=50` or \
         `VANILLITE_PERFORMANCE__TICK__PARALLEL_DIMENSIONS=false`. Empty variables are \
         ignored. `VANILLITE_EULA=true` accepts the \
         [Minecraft EULA](https://aka.ms/MinecraftEULA). `VANILLITE_LOG` sets the log level \
         (`error` to `trace`, default `info`). The console shows colours (WARN yellow, ERROR \
         red, `§` colour codes of chat, plugin messages and command output) on a terminal and \
         in Pterodactyl's console, otherwise plain text; `VANILLITE_COLOR=always` or `never` \
         overrides that, and `NO_COLOR` turns colours off.\n\n\
         ## Profiles\n\n\
         `profile` in `vanillite.toml` presets every rule; single keys override it. The \
         default is `paper`; set `profile = \"vanilla\"` for the most exact Vanilla behaviour. \
         A `vanillite.toml` without `profile` (written before `paper` became the default) gets \
         `profile = \"vanilla\"` written into it once, so the server keeps its behaviour.\n\n\
         | Profile | What |\n|---|---|\n",
    );
    for profile in Profile::ALL {
        let what = match profile {
            Profile::Vanilla => {
                "Vanilla behaviour, tick for tick: the most exact Vanilla behaviour. Deviates only \
                 to close security holes."
            }
            Profile::Technical => "Vanilla plus what technical players need.",
            Profile::Paper => {
                "Paper's defaults: behaves like a default Paper server (the default)."
            }
            Profile::Spigot => "Spigot's defaults, including Spigot's world folder layout.",
            Profile::Performance => {
                "Vanillite's strongest optimisations that change Vanilla behaviour only a little \
                 (activation range, merge radii, spawn and despawn tuning, overload protection)."
            }
            Profile::Crowd => {
                "`performance` plus crowd mode (`performance.crowd`) for thousands of players in \
                 one place: far players move less smoothly, each player sees only the nearest \
                 players, the locator bar updates less often."
            }
        };
        let _ = writeln!(out, "| `{}` | {what} |", profile.name());
    }
    out.push_str(
        "\n## server.properties\n\n\
         | Key | Default | Values | Description |\n|---|---|---|---|\n",
    );
    let mut defaults = BTreeMap::new();
    ServerProperties::default().write_to_map(&mut defaults);
    for info in ServerProperties::INFO {
        let values = match info.kind {
            PropertyKind::Bool => "`true`, `false`".to_owned(),
            PropertyKind::Integer => match info.range {
                Some((min, max)) => format!("integer, {min} to {max}"),
                None => "integer".to_owned(),
            },
            PropertyKind::Text => "text".to_owned(),
            PropertyKind::Enum(names) => names
                .iter()
                .map(|n| format!("`{n}`"))
                .collect::<Vec<_>>()
                .join(", "),
        };
        let default = defaults.get(info.key).map(String::as_str).unwrap_or("");
        let default = if default.is_empty() {
            "(empty)".to_owned()
        } else {
            format!("`{default}`")
        };
        let _ = writeln!(
            out,
            "| `{}` | {default} | {values} | {} |",
            info.key,
            cell(info.doc)
        );
    }
    out.push_str(
        "\n## vanillite.toml\n\n\
         Columns: the rule's value in each profile; *Restart*: a change takes effect after a \
         restart (all other rules are reloaded while the server runs). *Kind* says what a \
         rule is about: `security` (closes a security hole, always on, only its limits are \
         tunable), `exploit` (a Vanilla mechanic commonly called an exploit; Vanilla behaviour \
         by default), `fix` (a Vanilla bug fix), `gameplay`, `performance` (changes observable \
         behaviour for speed), `limit` (a limit Vanilla lacks that normal play does not reach) \
         and `setting` (no effect on game behaviour).\n\n\
         ### Server rules\n\n\
         These apply to the whole server.\n",
    );
    rules::<ServerRules>(&mut out);
    out.push_str(
        "\n### World rules\n\n\
         These can also be set per dimension in a section with the same keys, e.g.\n\n\
         ```toml\n[worlds.\"minecraft:the_nether\".performance.distances]\nview-distance = 8\n```\n",
    );
    rules::<WorldRules>(&mut out);
    out.push_str(
        "\n### Extra worlds\n\n\
         Worlds besides `level-name`, each with its own folder, `level.dat`, seed and generator \
         (see [Worlds](worlds.md#extra-worlds)), are loaded at startup from one section each. \
         Their rules come from `[worlds.\"minecraft:<name>\"]`.\n\n\
         ```toml\n[extra-worlds.lobby]\nenvironment = \"normal\"\ngenerator = \"flat\"\n\
         seed = \"\"\ngenerate-structures = true\n```\n\n\
         | Key | Default | Values | Description |\n|---|---|---|---|\n\
         | `environment` | `normal` | `normal`, `nether`, `the_end` | Its dimension type. |\n\
         | `generator` | `normal` | `normal`, `flat`, `void`, `amplified`, `large_biomes`, a dimension key | The terrain of a new world; a dimension key takes that dimension's generator. |\n\
         | `seed` | (empty) | text | The seed of a new world, like `level-seed`; empty for a random one. |\n\
         | `generate-structures` | `true` | `true`, `false` | Whether a new world gets structures. |\n",
    );
    out
}

/// One table per rule group.
fn rules<R: RuleSet>(out: &mut String) {
    let values: Vec<R> = Profile::ALL.into_iter().map(R::for_profile).collect();
    let mut group = "";
    for info in R::RULES {
        if info.group != group {
            group = info.group;
            let _ = write!(out, "\n#### `[{group}]`\n\n| Key | Kind | Restart |");
            for profile in Profile::ALL {
                let _ = write!(out, " `{profile}` |");
            }
            out.push_str(" Description |\n|---|---|---|");
            for _ in Profile::ALL {
                out.push_str("---|");
            }
            out.push_str("---|\n");
        }
        let kind = match info.kind {
            Kind::Security => "security",
            Kind::Exploit => "exploit",
            Kind::Fix => "fix",
            Kind::Gameplay => "gameplay",
            Kind::Performance => "performance",
            Kind::Limit => "limit",
            Kind::Setting => "setting",
        };
        let restart = if info.restart { "yes" } else { "" };
        let _ = write!(out, "| `{}` | {kind} | {restart} |", info.name);
        for rules in &values {
            let value = rules
                .get(info.key)
                .map(|v| format!("`{v}`"))
                .unwrap_or_default();
            let _ = write!(out, " {} |", value.replace('|', "\\|"));
        }
        let mut description = cell(info.doc);
        let ty = match info.value.ty {
            ValueType::Bool => "",
            ValueType::Integer => "Integer",
            ValueType::Number => "Number",
            ValueType::Text => "",
        };
        if !info.value.choices.is_empty() {
            let choices = info
                .value
                .choices
                .iter()
                .map(|c| format!("`\"{c}\"`"))
                .collect::<Vec<_>>()
                .join(", ");
            let _ = write!(description, " Values: {choices}.");
        } else if let Some((min, max)) = info.range {
            let _ = write!(description, " {ty} from {min} to {max}.");
        }
        if let Some(keyword) = info.value.keyword {
            let _ = write!(description, " Also accepts `\"{keyword}\"`.");
        }
        let _ = writeln!(
            out,
            " {} Environment: `{}`. |",
            description.trim(),
            env_name(info.key)
        );
    }
}

/// A doc comment as one table cell.
fn cell(doc: &str) -> String {
    doc.split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
        .replace('|', "\\|")
}
